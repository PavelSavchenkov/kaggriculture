"""Compile statically decoded King RC4 tables; never execute its policy."""
import hashlib
import json
from pathlib import Path
from generate_public_routes import triple

EXP = Path(__file__).resolve().parents[1]
DONOR = EXP / "research/refresh_0804/notebooks/yamakawanin/king-v4e-rc4"
TARGET = EXP / "league/king_rc4"


def main():
    program = json.loads((DONOR / "PROGRAM.json").read_text())
    markets = json.loads((DONOR / "MARKET_LIB.json").read_text())
    keys = list(program)
    values, offsets, examples, ranges = [], [], [], []
    for key, actions in program.items():
        phase = 0 if key == "OPENING" else int(key[1])
        for i, action in enumerate(actions):
            offsets.append(len(values))
            units = [action["farmer"], *action["hands"]]
            orders = action["market"]
            values += [len(units), len(orders)]
            for unit in units:
                values.extend(triple(unit))
            for order in orders:
                values.extend(triple(order, True))
            start = len(examples)
            for feat, orders in markets.get(str(phase * 72 + i), {}).get(key, []):
                assert len(feat) == 43 and len(orders) <= 10
                examples.append((feat, [triple(o, True) for o in orders]))
            ranges.append([start, len(examples)])
    block_starts, total = [], 0
    for actions in program.values():
        block_starts.append(total)
        total += len(actions)
    families = ["BAL", "MILK", "PET", "YARN_FIRST", "YARN_SECOND", "YARN_THIRD"]
    mapping = [[0] * 6]
    mapping.append([keys.index("S1_" + f) for f in ["BAL", "MILK", "PET", "YARN", "YARN", "YARN"]])
    mapping.append([keys.index("S2_" + f) for f in families[:5]] + [keys.index("S2_BAL")])
    mapping += [[keys.index(f"P{p}_{f}") for f in families] for p in range(3, 10)]
    def rows(name, data, width):
        return f"constexpr int {name}[][{width}]={{\n" + ",\n".join("{" + ",".join(map(str, x)) + "}" for x in data) + "\n};\n"
    code = "// Generated by scripts/generate_king_data.py; see IMPORT.json.\n"
    code += rows("block_map", mapping, 6)
    for name, data in [("block_start", block_starts), ("action_offset", offsets), ("action_data", values)]:
        code += f"constexpr int {name}[]={{\n" + ",\n".join(",".join(map(str, data[i:i+100])) for i in range(0, len(data), 100)) + "\n};\n"
    code += rows("example_range", ranges, 2)
    code += "constexpr MarketExample market_examples[]={\n"
    for feat, orders in examples:
        packed = ",".join("{" + ",".join(map(str, o)) + "}" for o in orders)
        code += "{{" + ",".join(map(str, feat)) + "}," + str(len(orders)) + ",{" + packed + "}},\n"
    code += "};\n"
    (TARGET / "source").mkdir(parents=True, exist_ok=True)
    (TARGET / "source/data.inc").write_text(code)
    report = {"blocks": len(keys), "actions": len(offsets), "market_examples": len(examples),
              "source_sha256": hashlib.sha256((DONOR / "extracted_main.py").read_bytes()).hexdigest(),
              "data_sha256": hashlib.sha256(code.encode()).hexdigest(), "block_keys": keys}
    (TARGET / "DATA.json").write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps({k: v for k, v in report.items() if k != "block_keys"}))


if __name__ == "__main__":
    main()
